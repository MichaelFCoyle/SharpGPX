        /// <summary>
        /// Read the GPX from the source file, take each route and 
        /// store it in a new GPX class
        /// </summary>
        /// <param name="sourceFileName"></param>
        /// <returns></returns>
        public static List<GpxClass> CopyGpxFile(string sourceFileName)
        {
            List<GpxClass> result = new List<GpxClass>();

            var source = GpxClass.FromFile(sourceFileName);

            foreach (var track in source.Tracks)
            {
                var newGPX = new GpxClass()
                {
                    Metadata = new metadataType()
                    {
                        name = track.name,
                        desc = track.desc,
                    },
                };

                var routes = track.ToRoutes();
                newGPX.Routes.AddRange(routes);

                var _ = newGPX.ToXml();

                result.Add(newGPX);
            }

            return result;
        }

        /// <summary>
        /// Convert tracks to routes
        /// </summary>
        /// <param name="sourceFileName"></param>
        /// <returns></returns>
        public static GpxClass ConvertToRoutes(string sourceFileName)
        {
            var src = GpxClass.FromFile(sourceFileName);

            var dst = new GpxClass()
            {
                Creator = src.Creator,
                Extensions = new extensionsType(src.Extensions),
                Metadata = new metadataType(src.Metadata),
            };

            foreach (var track in src.Tracks)
                dst.Routes.AddRange(track.ToRoutes());

            return dst;
        }

        /// <summary>
        /// Read and print a GPX file
        /// </summary>
        /// <param name="fileName"></param>
        public static string ReadAndPrint(string fileName)
        {
            StringBuilder sb = new StringBuilder();

            sb.AppendFormat("File Name: {0}\r\n", fileName);
            GpxClass gpx = GpxClass.FromFile(fileName);

            return sb.Append(gpx.Print()).ToString();
        }

        /// <summary>
        /// Print a GPX file
        /// </summary>
        /// <param name="gpx"></param>
        /// <returns></returns>
        public static string Print(this GpxClass gpx)
        {
            StringBuilder sb = new StringBuilder();
            sb.AppendFormat("{0} elements total\r\n", gpx.CountElements());

            sb.AppendFormat("Waypoints: {0}\r\n", gpx.Waypoints.Count);
            gpx.Waypoints.ForEach(x => sb.AppendLine(x.Print()));

            sb.AppendFormat("Routes: {0}\r\n", gpx.Routes.Count);
            gpx.Routes.ForEach(x => sb.AppendLine(x.Print()));

            sb.AppendFormat("Tracks: {0}\r\n", gpx.Tracks.Count);
            gpx.Tracks.ForEach(x => sb.AppendLine(x.Print()));

            return sb.ToString();
        }

